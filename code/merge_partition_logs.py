"""
Merge two logs of the same experiment into one, per (arm, seed).

Used when a run was interrupted and then repeated on different hardware: the
records are keyed by (arm, seed), and for each key the LAST file listed wins.
So listing the new run first and the old one second keeps the new records and
falls back to the old ones only for the (arm, seed) pairs the new run never
reached.

  # old = CPU run that got 23/35 arms, new = GPU run that did the rest
  python code/merge_partition_logs.py logs/ex1_yelp_gpu.out logs/ex1_yelp_serial.out \
      --out logs/ex1_yelp_merged.out

Only the per-run record lines are copied; the console summary at the end of a
log is regenerated by code/summarize_partition_logs.py, so it is dropped here.
"""

import re
import sys
import argparse

ARM_HDR = re.compile(r'^\s*---\s*ARM\s+([A-Z_]+)\s*\(seed\s+(\d+)\)\s*$')
ARM_LINE = re.compile(r'^\s*\[[A-Z_]+\]\s+R@10=')
# the two continuation lines that belong to the previous arm's record
CONT = ('partition quality:', 'load:')


def read_records(path):
    """-> list of (arm, seed, [lines...]) in file order."""
    out = []
    with open(path, encoding='utf-8', errors='replace') as f:
        lines = f.read().splitlines()
    i = 0
    while i < len(lines):
        m = ARM_HDR.match(lines[i])
        if m:
            arm, seed = m.group(1), int(m.group(2))
            block = [lines[i]]
            j = i + 1
            if j < len(lines) and ARM_LINE.match(lines[j]):
                block.append(lines[j])
                j += 1
                while j < len(lines) and any(lines[j].strip().startswith(c) for c in CONT):
                    block.append(lines[j])
                    j += 1
            out.append((arm, seed, block))
            i = j
            continue
        i += 1
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('logs', nargs='+',
                    help='logs in priority order: the first one wins for a '
                         'given (arm, seed)')
    ap.add_argument('--out', required=True)
    args = ap.parse_args()

    merged = {}      # (arm, seed) -> block
    order = []       # keep first-seen order
    for path in args.logs:
        try:
            recs = read_records(path)
        except OSError:
            print(f'[skip] {path} (not found)')
            continue
        kept = 0
        for arm, seed, block in recs:
            key = (arm, seed)
            if key in merged:
                continue          # an earlier file already provided this pair
            merged[key] = block
            order.append(key)
            kept += 1
        print(f'[read] {path}: {len(recs)} records, {kept} new')

    with open(args.out, 'w', encoding='utf-8') as f:
        for key in order:
            for ln in merged[key]:
                f.write(ln + '\n')

    print(f'[written] {args.out}: {len(order)} (arm, seed) records')
    seeds = sorted({s for _, s in merged})
    arms = sorted({a for a, _ in merged})
    print(f'  seeds={seeds}  arms={arms}')
    # point out the gaps
    missing = [(a, s) for s in seeds for a in arms if (a, s) not in merged]
    if missing:
        print(f'  MISSING {len(missing)} pairs: {missing}')


if __name__ == '__main__':
    main()
